// ctx 域设计:无状态——终结动作全部经 YomkServerRef 快照取当前 server,未初始化守卫内聚在守卫与请求域一层;
// 依赖单向(Request/ContextUrl/Msg/Payload),不依赖其他域头,可独立包含.
/**
 * @brief Chained builder for context key-value, reads and writes contexts within a specified group
 *
 * @par Typed read
 * yomk::ctx().key(n).group(g).msg<T>().with_default(d).get()
 * @li kName comparison + dynamic_pointer_cast, returns shared_ptr<T>
 * @li T is a message class generated by YOMK_DEFINE_MSG, guarded by static_assert
 * @li .with_default(d) may be omitted: falls back to nullptr on miss
 *
 * @par Write path
 * @li yomk::ctx().key(n).group(g).value(ctx).create(): create a context key-value
 * @li yomk::ctx().key(n).group(g).value(ctx).set(): replace the whole context value
 * @li yomk::ctx().key(n).group(g).destroy(): destroy the specified context key
 * @li yomk::ctx().key(n).group(g).checker_fn(fn).apply(): set the key-level checker gating callback
 * @li yomk::ctx().key(n).group(g).monitor_fn(fn).async(on).apply(): set the key-level change monitor callback,
 *     on = true for asynchronous notification; .async(on) may be omitted, default on = false (synchronous)
 * @li .value(ctx) sets the context value, a YOMK_DEFINE_MSG message object, shared by create/set
 * @li All of the above return the three-state ResStatus
 *
 * @par Group-level switches (facets, all return the three-state ResStatus)
 * @li yomk::ctx().group(g).checker().enable() / .checker().disable(): checker gating switch
 * @li yomk::ctx().group(g).monitor().enable() / .monitor().disable(): change monitor switch
 *
 * @par Introspection queries
 * @li yomk::ctx().group(g).keys(): all context key names within the group, returns Response
 * @li yomk::ctx().key(n).group(g).info(): status of the specified context key, returns Response
 * @li yomk::ctx().groups(): list of all group names, returns Response (StringArray)
 * @li yomk::ctx().all(): introspection metadata of all groups and all their keys, returns Response (ContextGroupInfoList)
 *
 * @par Other notes
 * @li key/group accumulate as views; omitting group name g defaults to "main"
 * @li The read path returns Invalid if uninitialized and logs diagnostics; three-state convergence of the write path is carried by the request domain .status()
 *
 * @warning The builder holds key/group views, use inline in a single expression only, never cache or reuse the builder, otherwise dangling references!
 */
// @zh: 上下文键值链式 Builder，读写指定组内的上下文
// @zh: par 类型化读
// @zh: li kName 比对 + dynamic_pointer_cast，返回 shared_ptr<T>
// @zh: li T 为 YOMK_DEFINE_MSG 消息类，static_assert 把关
// @zh: li .with_default(d) 可省略：未命中回退 nullptr
// @zh: par 写路径
// @zh: li yomk::ctx().key(n).group(g).value(ctx).create()：创建上下文键值
// @zh: li yomk::ctx().key(n).group(g).value(ctx).set()：整体替换上下文值
// @zh: li yomk::ctx().key(n).group(g).destroy()：销毁指定上下文键
// @zh: li yomk::ctx().key(n).group(g).checker_fn(fn).apply()：设置键级校验门控回调
// @zh: li yomk::ctx().key(n).group(g).monitor_fn(fn).async(on).apply()：设置键级变更监听回调，
// @zh:     on = true 异步通知；.async(on) 可省略，缺省 on = false（同步）
// @zh: li .value(ctx) 设置上下文值，YOMK_DEFINE_MSG 消息对象，create/set 共用
// @zh: li 以上均返回三态 ResStatus
// @zh: par 组级开关（分面，均返回三态 ResStatus）
// @zh: li yomk::ctx().group(g).checker().enable() / .checker().disable()：校验门控开关
// @zh: li yomk::ctx().group(g).monitor().enable() / .monitor().disable()：变更监听开关
// @zh: par 内省查询
// @zh: li yomk::ctx().group(g).keys()：组内全部上下文键名，返回 Response
// @zh: li yomk::ctx().key(n).group(g).info()：指定上下文键状态，返回 Response
// @zh: li yomk::ctx().groups()：全部组名清单，返回 Response（StringArray）
// @zh: li yomk::ctx().all()：全部组及其全部键的内省元信息，返回 Response（ContextGroupInfoList）
// @zh: par 其他说明
// @zh: li key/group 为 view 累积，组名 g 省略即缺省 "main"
// @zh: li 读路径未初始化返回 Invalid 并记录诊断信息；写路径三态收敛由请求域 .status() 承担
// @zh: warning Builder 持 key/group 视图，仅限单表达式内联使用，禁止缓存复用，否则悬垂引用！
// 公开面仅暴露域入口, builder/分面类机制内敛, 调用方全程以 auto 接收,从不具名引用类型
namespace yomk::detail
{
class ContextBuilder;  // 前置声明,定义见下方机制段
}

#pragma once
#include <memory>
#include <string>
#include <utility>

/**
 * @brief Base class of message types: carrier of the runtime type name (compared against kName)
 * @note Custom messages are derived via the YOMK_DEFINE_MSG macro, not by inheriting this class
 *       and naming it manually
 */
// @zh: 消息类型基类：运行时类型名载体（kName 比对对象）
// @zh: note 自定义消息经 YOMK_DEFINE_MSG 宏派生，不直接继承本类手工命名
class YomkMsg
{
public:
    YomkMsg() {}
    virtual ~YomkMsg() {}

public:
    void name(const std::string& name) { m_name = name; }
    std::string name() { return m_name; }

protected:
    std::string m_name;
};
using YomkMsgPtr = std::shared_ptr<YomkMsg>;

/**
 * @brief Define a message type: generate the YomkMsg derived class MsgName inside yomk::msgs
 * @param DataType Payload data type
 * @param MsgName Message class name (also serves as the type identifier kName, used for unpack
 *        and dynamic lookup comparison)
 * @param VarName Payload member name (framework convention fixes it to d, e.g. pkg->d)
 * @note The generated class provides the shared(...) factory; custom messages are declared only
 *       by this macro, see YomkStdMsg.h for the standard type message catalog, YomkServerMsg.h
 *       for the core payload message catalog, and each Yomk{Module}Msg.h for module-specific
 *       message catalogs
 */
// @zh: 定义消息类型：在 yomk::msgs 内生成 YomkMsg 派生类 MsgName
// @zh: DataType 载荷数据类型
// @zh: MsgName 消息类名（同时作为类型标识 kName，供解包/动态查找比对）
// @zh: VarName 载荷成员名（框架约定统一为 d，如 pkg->d）
// @zh: note 生成类提供 shared(...) 工厂；自定义消息仅此宏声明，标准类型消息目录见 YomkStdMsg.h，核心载荷消息目录见 YomkServerMsg.h，模块专属消息目录见各 Yomk{Module}Msg.h
#define YOMK_DEFINE_MSG(DataType, MsgName, VarName)                               \
    namespace yomk::msgs                                                          \
    {                                                                             \
    class MsgName : public ::YomkMsg                                              \
    {                                                                             \
    public:                                                                       \
        static constexpr const char* kName = #MsgName;                            \
        MsgName() { m_name = kName; }                                             \
        MsgName(const DataType& value) : VarName(value) { m_name = kName; }       \
        MsgName(DataType&& value) : VarName(std::move(value)) { m_name = kName; } \
        virtual ~MsgName() {}                                                     \
                                                                                  \
    public:                                                                       \
        DataType VarName{};                                                       \
                                                                                  \
        template <typename... A>                                                  \
        static std::shared_ptr<MsgName> shared(A&&... a)                          \
        {                                                                         \
            return std::make_shared<MsgName>(std::forward<A>(a)...);              \
        }                                                                         \
    };                                                                            \
    using MsgName##Ptr = std::shared_ptr<MsgName>;                                \
    }

namespace yomk::msgs
{

/**
 * @brief Runtime type name of a message, null-safe
 * @param pkg Message pointer, may be empty
 * @return The message's type name; "null" when pkg is empty.
 *         Intended for error messages that report the actual type received
 */
// @zh: 消息的运行时类型名，判空安全
// @zh: pkg 消息指针，可为空
// @zh: return 类型名；pkg 为空返回 "null"。
// @zh:      用于错误文案报出"实际收到的类型"（具体值原则：期望/实际类型一并输出）
inline std::string typeOf(const YomkMsgPtr& pkg)
{
    return pkg ? pkg->name() : "null";
}

/**
 * @brief Unpack a message by its runtime type name
 * @tparam Msg Target message class (generated by YOMK_DEFINE_MSG)
 * @param pkg Pointer to the message to unpack
 * @return shared_ptr<Msg> on hit; nullptr if pkg is empty or the type does not match
 * @note Usable directly as a null check, throws no exceptions
 */
// @zh: 按运行时类型名解包消息
// @zh: Msg 目标消息类（YOMK_DEFINE_MSG 生成）
// @zh: pkg 待解包消息指针
// @zh: return 命中返回 shared_ptr<Msg>；pkg 为空或类型不符返回 nullptr
// @zh: note 判空即用，不抛异常
template <class Msg>
std::shared_ptr<Msg> unpack(const YomkMsgPtr& pkg)
{
    if (pkg && pkg->name() == Msg::kName)
    {
        return std::dynamic_pointer_cast<Msg>(pkg);
    }
    return nullptr;
}

}  // namespace yomk::msgs

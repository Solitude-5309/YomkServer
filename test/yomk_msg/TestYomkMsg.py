def check(cond, msg):
    # [ OK ]/[FAIL] [行号] 行输出 + 失败计数
    global g_failed
    line = sys._getframe(1).f_lineno
    if cond:
        print(f"[ OK ] [line {line}] {msg}")
    else:
        print(f"[FAIL] [line {line}] {msg}")
        g_failed += 1


# ============ S1. TYPE_NAME 生成契约（模块级类：qualname 无作用域段） ============
class S1AutoMsg(YomkMsg):
    pass


class S1ChildMsg(String):
    pass


def s1_type_name_rules():
    print("===== S1. TYPE_NAME 生成契约 =====")

    # 规则 B + 顶层回退：脚本顶层运行，__module__ = "__main__"（无父包）
    # → 回退用完整 __module__ 拼接
    check(S1AutoMsg.TYPE_NAME == "__main__.S1AutoMsg",
          f"规则 B 顶层回退: {S1AutoMsg.TYPE_NAME!r}")

    # 动态 type() 注入自定义 __module__：取最近一级父包（最后一段是模块名，剥掉）
    widget = type("Widget", (YomkMsg,), {"__module__": "app.widget"})
    check(widget.TYPE_NAME == "app.Widget", f"规则 B 父包拼接: {widget.TYPE_NAME!r}")

    # 深层父包：同理剥掉末段模块名
    deep = type("Deep", (YomkMsg,), {"__module__": "a.b.c.mod"})
    check(deep.TYPE_NAME == "a.b.c.Deep", f"深层父包剥文件段: {deep.TYPE_NAME!r}")

    # 类体显式定义 TYPE_NAME：类型名只能由框架生成，定义即 TypeError
    # （对齐 C++：自定义消息只能经 YOMK_DEFINE_MSG 宏生成）
    try:
        class S1OverrideMsg(YomkMsg):
            TYPE_NAME = "override::name"
        check(False, "类体定义 TYPE_NAME 应抛 TypeError")
    except TypeError as e:
        check(str(e) == "TYPE_NAME is generated by YomkMsg, "
                        "do not define it in the class body",
              "类体定义 TYPE_NAME → TypeError 文案一致")

    # 孙类再生成：未显式定义的子类自动获得与父类不同的 TYPE_NAME
    check(S1ChildMsg.TYPE_NAME == "__main__.S1ChildMsg",
          f"孙类再生成: {S1ChildMsg.TYPE_NAME!r}")
    check(S1ChildMsg.TYPE_NAME != String.TYPE_NAME, "子类 TYPE_NAME 必然不同于父类")

    # qualname 保真：函数内定义的类带作用域段（<locals>），如实入名
    class S1LocalMsg(YomkMsg):
        pass

    check(".<locals>." in S1LocalMsg.TYPE_NAME,
          f"函数作用域 qualname 保真: {S1LocalMsg.TYPE_NAME!r}")

    # 基类自身 TYPE_NAME 为空字面量（不参与比对）
    check(YomkMsg.TYPE_NAME == "", "基类 TYPE_NAME 为空")

    # 只读常量：生成后类上重绑定/删除、实例上赋值/删除一律 AttributeError
    # （对齐 C++ static constexpr；防止实例属性遮蔽类型名）
    try:
        String.TYPE_NAME = "override::name"
        check(False, "类上重绑定 TYPE_NAME 应抛 AttributeError")
    except AttributeError as e:
        check(str(e) == "TYPE_NAME is a read-only class constant",
              "类上重绑定 TYPE_NAME → AttributeError 文案一致")

    try:
        del String.TYPE_NAME
        check(False, "类上删除 TYPE_NAME 应抛 AttributeError")
    except AttributeError as e:
        check(str(e) == "TYPE_NAME is a read-only class constant",
              "类上删除 TYPE_NAME → AttributeError 文案一致")

    probe = String("x")
    try:
        probe.TYPE_NAME = "hacked.by.instance"
        check(False, "实例上赋值 TYPE_NAME 应抛 AttributeError")
    except AttributeError as e:
        check(str(e) == "TYPE_NAME is a read-only class constant",
              "实例上赋值 TYPE_NAME → AttributeError 文案一致")

    try:
        del probe.TYPE_NAME
        check(False, "实例上删除 TYPE_NAME 应抛 AttributeError")
    except AttributeError as e:
        check(str(e) == "TYPE_NAME is a read-only class constant",
              "实例上删除 TYPE_NAME → AttributeError 文案一致")

    check(probe.TYPE_NAME == String.TYPE_NAME == "yomk.msgs.String",
          "实例读与类型读均为生成值，未被篡改")


# ============ S2. std 类结构契约 ============
def s2_std_classes():
    print("===== S2. std 类结构契约 =====")

    # 9 个 std 类 TYPE_NAME 字面断言（全限定形态，对齐 C++ 全限定口径）
    expected_type_names = {
        Bool: "yomk.msgs.Bool",
        Int: "yomk.msgs.Int",
        Float: "yomk.msgs.Float",
        String: "yomk.msgs.String",
        Bytes: "yomk.msgs.Bytes",
        BoolArray: "yomk.msgs.BoolArray",
        IntArray: "yomk.msgs.IntArray",
        FloatArray: "yomk.msgs.FloatArray",
        StringArray: "yomk.msgs.StringArray",
    }
    for cls, type_name in expected_type_names.items():
        check(cls.TYPE_NAME == type_name, f"{cls.__name__}.TYPE_NAME == {type_name!r}")

    # 标量字段 value：默认值 + 构造透传
    check(Bool().value is False, "Bool 默认 value=False")
    check(Bool(True).value is True, "Bool(True) 透传")
    check(Int().value == 0, "Int 默认 value=0")
    check(Int(42).value == 42, "Int(42) 透传")
    check(Float().value == 0.0, "Float 默认 value=0.0")
    check(Float(1.5).value == 1.5, "Float(1.5) 透传")
    check(String().value == "", "String 默认 value=''")
    check(String("hello").value == "hello", "String('hello') 透传")
    check(Bytes().value == b"", "Bytes 默认 value=b''")
    check(Bytes(b"\x00\x01").value == b"\x00\x01", "Bytes 透传")

    # 数组字段 items：默认空 list + 构造透传（None 归一为空 list）
    for cls in (BoolArray, IntArray, FloatArray, StringArray):
        check(cls().items == [], f"{cls.__name__}() 默认 items==[]")
        check(cls(None).items == [], f"{cls.__name__}(None) 归一为 []")

    check(BoolArray([True, False]).items == [True, False], "BoolArray 透传")
    check(IntArray([1, 2]).items == [1, 2], "IntArray 透传")
    check(FloatArray([0.5]).items == [0.5], "FloatArray 透传")
    check(StringArray(["a"]).items == ["a"], "StringArray 透传")


# ============ S3. unpack 语义（结果对象） ============
def s3_unpack():
    print("===== S3. unpack 语义（结果对象） =====")

    s = String("hit")

    # 命中：结果判真，msg 为原对象（同一实例，非拷贝），error 为空串
    hit = unpack(s, String)
    check(bool(hit) is True, "命中 → 判真")
    check(hit.msg is s, "命中 msg 为原对象")
    check(hit.error == "", "命中 error 为空串")

    # 跨类型未命中：判假，msg 为 None
    miss = unpack(Int(1), String)
    check(bool(miss) is False, "跨类型未命中 → 判假")
    check(miss.msg is None, "跨类型未命中 msg 为 None")
    check(not unpack(BoolArray([True]), StringArray), "数组跨类型未命中 → 判假")

    # 子类不冒充父类：子类自动 TYPE_NAME 与父类不同（精确身份匹配）
    class S3SubString(String):
        pass

    check(not unpack(S3SubString("sub"), String),
          "子类实例解包为父类 → 判假（精确身份匹配）")
    check(bool(unpack(S3SubString("sub"), S3SubString)),
          "子类对自身解包命中")

    # A 方案精确身份语义：裸 str 不是 String 消息
    check(not unpack("bare", String), "裸 str 对 String 被拒")

    # None 入参：判假；与 is_msg_instance 的 None 判定无关
    check(not unpack(None, String), "None → 判假")
    check(unpack(None, String).error
          == "msg is not yomk.msgs.String, got 'null'",
          "None → 空包文案 got 'null'")

    # 非消息类/基类不是 unpack 的合法目标：直接 TypeError（无退化 isinstance）
    for cls, name in ((str, "str"), (int, "int"), (YomkMsg, "YomkMsg")):
        try:
            unpack("text", cls)
            check(False, f"unpack 目标 {name} 应抛 TypeError")
        except TypeError as e:
            check(str(e) == "unpack requires a concrete YomkMsg subclass, got '"
                            + name + "'",
                  f"unpack 目标 {name} → TypeError 文案一致")

    # 非类入参同样 TypeError，文案报宿主类名
    try:
        unpack("text", "str")
        check(False, "unpack 目标为非类应抛 TypeError")
    except TypeError as e:
        check(str(e) == "unpack requires a concrete YomkMsg subclass, got 'str'",
              "unpack 非类目标 → TypeError 文案一致")

    # None 作目标走内部取值空包态；入参 None 不再前置短路，同样先校验 cls
    for arg, who in (("text", "unpack 目标为 None"), (None, "unpack 入参与目标均为 None")):
        try:
            unpack(arg, None)
            check(False, who + " 应抛 TypeError")
        except TypeError as e:
            check(str(e) == "unpack requires a concrete YomkMsg subclass, got 'null'",
                  who + " → TypeError 文案一致")


# ============ S4. 内部取值四态（诊断文案共用） ============
def s4_type_name_of():
    print("===== S4. 内部取值四态（诊断文案共用） =====")

    # is_msg_instance：require_msg_payload / unpack / 内部取值共用实例判据
    check(is_msg_instance(String("x")) is True, "具体消息实例 → True")
    check(is_msg_instance(StringArray(["a"])) is True, "数组实例 → True")
    check(is_msg_instance(None) is False, "None → False（None 由调用方判定）")
    check(is_msg_instance(YomkMsg()) is False, "直基类实例 → False")
    check(is_msg_instance("bare") is False, "裸 str → False")
    check(is_msg_instance(String) is False, "类对象 → False")

    # is_msg_subclass：require_msg_subclass / unpack 共用的类域判据
    check(is_msg_subclass(String) is True, "具体消息类 → True")
    check(is_msg_subclass(StringArray) is True, "数组消息类 → True")
    check(is_msg_subclass(YomkMsg) is False, "基类 → False")
    check(is_msg_subclass(str) is False, "体系外类 → False")
    check(is_msg_subclass("str") is False, "非类 → False")
    check(is_msg_subclass(None) is False, "None → False")

    # require_msg_subclass：类域守卫，与 require_msg_payload 成对
    require_msg_subclass(String, "probe()")
    check(True, "具体消息类 → 不抛")
    try:
        require_msg_subclass(YomkMsg, "probe()")
        check(False, "基类应抛 TypeError")
    except TypeError as e:
        check(str(e) == "probe() requires a concrete YomkMsg subclass, got 'YomkMsg'",
              "基类 → TypeError 文案一致")

    # 第一态：YomkMsg 实例 → TYPE_NAME
    check(_yomk_type_name_of(String("x")) == "yomk.msgs.String", "消息实例 → TYPE_NAME")
    check(_yomk_type_name_of(Int(1)) == "yomk.msgs.Int", "Int 实例 → TYPE_NAME")
    check(_yomk_type_name_of(StringArray(["a"])) == "yomk.msgs.StringArray", "数组实例 → TYPE_NAME")

    # 第二态：None → "null"（对齐 C++ typeMismatch 的空包语义）
    check(_yomk_type_name_of(None) == "null", "None → 'null'")

    # 第三态：类对象 → 类自身名（cls 实参诊断；含消息子类，不报元类名 "type"）
    check(_yomk_type_name_of(String) == "String", "消息类对象 → 类名")
    check(_yomk_type_name_of(str) == "str", "内建类对象 → 类名")
    check(_yomk_type_name_of(YomkMsg) == "YomkMsg", "基类对象 → 类名")
    check(_yomk_type_name_of(type("Loose", (), {})) == "Loose", "体系外类对象 → 类名")

    # 第四态：非类对象 → 宿主类名，不冒充框架类型名或空包
    check(_yomk_type_name_of("bare") == "str", "裸 str → 宿主类名")
    check(_yomk_type_name_of(123) == "int", "int → 宿主类名")
    check(_yomk_type_name_of(["raw"]) == "list", "裸 list → 宿主类名")
    check(_yomk_type_name_of(lambda: 1) == "function", "函数 → 宿主类名")
    check(_yomk_type_name_of(YomkMsg()) == "YomkMsg", "直接基类实例 → 宿主类名")


# ============ S5. UnpackResult 契约 ============
def s5_unpack_result():
    print("===== S5. UnpackResult 契约 =====")

    s = String("hit")
    hit = unpack(s, String)
    check(isinstance(hit, UnpackResult), "命中结果为 UnpackResult")
    check(bool(hit) is True and hit.msg is s and hit.error == "",
          "命中：判真 / msg 同一实例 / error 为空串")
    check(repr(hit).startswith("UnpackResult(msg="),
          "命中 repr 含 UnpackResult 与 msg")

    miss = unpack(Int(1), String)
    check(bool(miss) is False and miss.msg is None,
          "未命中：判假 / msg 为 None")
    check(repr(miss).startswith("UnpackResult(error="),
          "未命中 repr 含 UnpackResult 与 error")

    # 标准文案四组：期望侧为 cls.TYPE_NAME，实际侧四态取值
    check(unpack(None, String).error
          == "msg is not yomk.msgs.String, got 'null'",
          "None 入参文案（got 侧 'null'）")
    check(unpack(Bool(True), String).error
          == "msg is not yomk.msgs.String, got 'yomk.msgs.Bool'",
          "消息实例入参文案（got 侧报 TYPE_NAME）")
    check(unpack("bare", String).error
          == "msg is not yomk.msgs.String, got 'str'",
          "体系外对象文案（got 侧报宿主类名，不冒充 null）")
    check(unpack(Int(1), Bool).error
          == "msg is not yomk.msgs.Bool, got 'yomk.msgs.Int'",
          "期望/实际双侧均为 TYPE_NAME")

    # 出口只读：赋值即 AttributeError（对齐 C++ 只读出口）
    for attr, value in (("msg", None), ("error", "x")):
        try:
            setattr(hit, attr, value)
            check(False, f"UnpackResult.{attr} 应只读")
        except AttributeError:
            check(True, f"UnpackResult.{attr} 只读 → AttributeError")



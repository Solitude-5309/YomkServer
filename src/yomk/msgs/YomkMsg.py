"""Message base class, typed unpacking and failure text.

消息基类、类型化解包与失败文案：TYPE_NAME 继承即得、随重命名自动跟随；unpack 返回
UnpackResult（判真取 msg、判假取 error），标准不符文案由 unpack 生成，实际类型名
取值私有化。
"""

_READ_ONLY = "TYPE_NAME is a read-only class constant"


class _TypeNameValue:
    # 只读类型名常量：数据描述符，实例写入/删除一律 AttributeError
    __slots__ = ("_value",)

    def __init__(self, value):
        self._value = value

    def __get__(self, obj, owner=None):
        return self._value

    def __set__(self, obj, value):
        raise AttributeError(_READ_ONLY)

    def __delete__(self, obj):
        raise AttributeError(_READ_ONLY)

    def __repr__(self):
        return repr(self._value)


class _YomkMsgMeta(type):
    # 类级封印：TYPE_NAME 一经生成，类上重绑定与删除一律 AttributeError
    def __setattr__(cls, name, value):
        if name == "TYPE_NAME" and "TYPE_NAME" in cls.__dict__:
            raise AttributeError(_READ_ONLY)
        type.__setattr__(cls, name, value)

    def __delattr__(cls, name):
        if name == "TYPE_NAME":
            raise AttributeError(_READ_ONLY)
        type.__delattr__(cls, name)


class YomkMsg(metaclass=_YomkMsgMeta):
    """Message base class; every subclass gets a qualified runtime type name.

    消息基类：子类自动获得全限定运行期类型名，供 unpack 比对与文案使用。

    Note:
        ``TYPE_NAME`` is a class constant (PEP 8 upper snake case, no ``k``
        prefix) generated as ``<parent package>.<qualified name>``; it must not
        be written by hand. Defining it in a class body raises ``TypeError``,
        matching C++ messages that can only be generated by ``YOMK_DEFINE_MSG``.
        It is read-only once generated: rebinding or deleting it on the class,
        or assigning it on an instance, raises ``AttributeError``, mirroring a
        C++ ``static constexpr`` constant.
        ``TYPE_NAME`` 按 Python 类常量惯例命名（全大写下划线，不带 C++ 的 k 前缀），
        由 ``<父包>.<限定名>`` 自动生成、随重命名跟随，禁止手写；类体显式定义直接
        ``TypeError``，对齐 C++ 只能经 ``YOMK_DEFINE_MSG`` 生成的口径。生成后即为
        只读常量：类上重绑定/删除、实例上赋值均抛 ``AttributeError``，对齐 C++
        ``static constexpr``。
    """

    TYPE_NAME = _TypeNameValue("")   # 基类自身不参与比对

    def __init_subclass__(cls, **kwargs):
        super().__init_subclass__(**kwargs)
        if "TYPE_NAME" in cls.__dict__:
            raise TypeError("TYPE_NAME is generated by YomkMsg, "
                            "do not define it in the class body")
        mod = cls.__module__
        parent, _, _ = mod.rpartition(".")
        # 唯一合法写入点：绕过元类封印，直接落只读描述符
        type.__setattr__(cls, "TYPE_NAME",
                         _TypeNameValue((parent if parent else mod)
                                        + "." + cls.__qualname__))


class UnpackResult:
    """Outcome of unpack: the decoded message and the failure reason.

    解包结果：判真时 ``msg`` 为命中消息、``error`` 为空串；判假时 ``msg`` 为 None、
    ``error`` 为标准文案。对齐 C++ ``UnpackResult<Msg>``——单一对象同时承载解码结果与
    失败原因，期望类型名只在 ``unpack`` 内书写一次。两个出口均为只读属性（C++ 侧出口
    恒为 const）。
    """

    __slots__ = ("_msg", "_error")

    def __init__(self, msg, error):
        self._msg = msg
        self._error = error

    def __bool__(self):
        return self._msg is not None

    @property
    def msg(self):
        return self._msg

    @property
    def error(self):
        return self._error

    def __repr__(self):
        if self._msg is not None:
            return "UnpackResult(msg=" + repr(self._msg) + ")"
        return "UnpackResult(error=" + repr(self._error) + ")"


def is_msg_instance(msg):
    """Return True only for a concrete YomkMsg instance.

    实例判据：仅具体消息子类实例为真；``None``（空载荷）、YomkMsg 直基类实例、
    类对象与体系外对象均为假。``None`` 的合法性由调用方自行判定。
    """
    return isinstance(msg, YomkMsg) and type(msg) is not YomkMsg


def is_msg_subclass(cls):
    """Return True only for concrete YomkMsg subclasses.

    类域判据：仅具体消息子类（类对象本身）为真；基类、非类与体系外类均为假。
    """
    return (isinstance(cls, type) and issubclass(cls, YomkMsg)
            and cls is not YomkMsg)


def require_msg_payload(msg, who):
    """Raise TypeError unless msg is a concrete YomkMsg instance or None.

    类型契约守卫：msg 必须是具体消息实例或 None（空载荷），否则入口当场
    ``TypeError``。直接基类实例不可用（C++ 侧 YomkMsg 为抽象类），同样拒绝。
    """
    if msg is None or is_msg_instance(msg):
        return
    raise TypeError(who + " requires a YomkMsg instance or None, got '"
                    + _yomk_type_name_of(msg) + "'")


def require_msg_subclass(cls, who):
    """Raise TypeError unless cls is a concrete YomkMsg subclass.

    类域守卫：cls 必须是具体消息子类，否则当场 ``TypeError``；基类与
    非类同样拒绝。与 require_msg_payload 成对，分别守类域与载荷入口。
    """
    if is_msg_subclass(cls):
        return
    raise TypeError(who + " requires a concrete YomkMsg subclass, got '"
                    + _yomk_type_name_of(cls) + "'")


def unpack(msg, cls):
    """Return an UnpackResult carrying the decoded message or the failure reason.

    按 TYPE_NAME 精确比对解包：命中时结果判真，``msg`` 为传入实例本身；未命中时结果
    判假，``msg`` 为 None、``error`` 为标准文案（空包报 ``got 'null'``）。不做类型边界
    探测，msg 可为 None 或体系外对象。cls 必须是具体消息类，否则 ``TypeError``。子类
    因 TYPE_NAME 不同不会被当作父类实例命中，这是设计行为。
    """
    require_msg_subclass(cls, "unpack")
    if is_msg_instance(msg) and type(msg).TYPE_NAME == cls.TYPE_NAME:
        return UnpackResult(msg, "")
    return UnpackResult(None, "msg is not " + cls.TYPE_NAME
                        + ", got '" + _yomk_type_name_of(msg) + "'")


def _yomk_type_name_of(msg):
    """Return the runtime type name of a message, or a descriptive name otherwise.

    内部取值：返回消息的运行期类型名（TYPE_NAME）；None 返回 "null"，类对象返回其类名，
    其余返回宿主类名，从不以 "null" 掩盖误用。仅供 unpack / require_* 与 ctx 诊断文案
    使用；公开面直连只读 ``TYPE_NAME``，本函数不导出。
    """
    if msg is None:
        return "null"
    if is_msg_instance(msg):
        return type(msg).TYPE_NAME
    if isinstance(msg, type):
        return msg.__name__
    return type(msg).__name__

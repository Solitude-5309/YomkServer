"""Message base class, typed unpacking and type diagnostics.

消息基类、类型化解包与类型诊断：TYPE_NAME 继承即得、随重命名自动跟随；unpack 未命中
返回 None；type_name_of / type_mismatch 生成标准错误文案。
"""


class YomkMsg:
    """Message base class; every subclass gets a qualified runtime type name.

    消息基类：子类自动获得全限定运行期类型名，供 unpack 比对与文案使用。

    Note:
        ``TYPE_NAME`` is a class constant (PEP 8 upper snake case, no ``k``
        prefix) generated as ``<parent package>.<qualified name>``; it must not
        be written by hand. Defining it in a class body raises ``TypeError``,
        matching C++ messages that can only be generated by ``YOMK_DEFINE_MSG``.
        ``TYPE_NAME`` 按 Python 类常量惯例命名（全大写下划线，不带 C++ 的 k 前缀），
        由 ``<父包>.<限定名>`` 自动生成、随重命名跟随，禁止手写；类体显式定义直接
        ``TypeError``，对齐 C++ 只能经 ``YOMK_DEFINE_MSG`` 生成的口径。
    """

    TYPE_NAME = ""                  # 基类自身不参与比对

    def __init_subclass__(cls, **kwargs):
        super().__init_subclass__(**kwargs)
        if "TYPE_NAME" in cls.__dict__:
            raise TypeError("TYPE_NAME is generated by YomkMsg, "
                            "do not define it in the class body")
        mod = cls.__module__
        parent, _, _ = mod.rpartition(".")
        cls.TYPE_NAME = (parent if parent else mod) + "." + cls.__qualname__


def is_msg_instance(v):
    """Return True only for concrete YomkMsg subclass instances.

    判据：仅具体消息子类实例为真；None、YomkMsg 直基类实例与体系外对象均为假。
    """
    return isinstance(v, YomkMsg) and type(v) is not YomkMsg


def is_msg_subclass(cls):
    """Return True only for concrete YomkMsg subclasses.

    类域判据：仅具体消息子类（类对象本身）为真；基类、非类与体系外类均为假。
    """
    return (isinstance(cls, type) and issubclass(cls, YomkMsg)
            and cls is not YomkMsg)


def require_msg(v, who):
    """Raise TypeError unless v is a concrete YomkMsg instance or None.

    类型契约守卫：v 必须是具体消息实例或 None（空载荷），否则入口当场
    ``TypeError``。直接基类实例不可用（C++ 侧 YomkMsg 为抽象类），同样拒绝。
    """
    if v is None or is_msg_instance(v):
        return
    raise TypeError(who + " requires a YomkMsg instance or None, got '"
                    + type_name_of(v) + "'")


def unpack(pkg, cls):
    """Return pkg when it matches cls by TYPE_NAME, otherwise None.

    按 TYPE_NAME 精确比对解包，未命中返回 None，不抛异常；pkg 可为 None 或体系外
    对象（无类型边界探测）。cls 必须是具体消息类，否则 ``TypeError``。子类因
    TYPE_NAME 不同不会被当作父类实例命中，这是设计行为。
    """
    if not is_msg_subclass(cls):
        raise TypeError("unpack requires a concrete YomkMsg subclass, got '"
                        + type_name_of(cls) + "'")
    if is_msg_instance(pkg) and type(pkg).TYPE_NAME == cls.TYPE_NAME:
        return pkg
    return None


def type_name_of(pkg):
    """Return the runtime type name of a message, or a descriptive name otherwise.

    返回消息的运行期类型名（TYPE_NAME）；None 返回 "null"，类对象返回其类名，
    其余返回宿主类名，从不以 "null" 掩盖误用。对应 C++ ``typeNameOf``。
    """
    if pkg is None:
        return "null"
    if is_msg_instance(pkg):
        return type(pkg).TYPE_NAME
    if isinstance(pkg, type):
        return pkg.__name__
    return type(pkg).__name__


def type_mismatch(pkg, expected):
    """Build the standard type-mismatch text, expecting ``cls.TYPE_NAME``.

    构造标准类型不符文案；expected 由调用方传 ``cls.TYPE_NAME``。
    """
    return "pkg is not " + expected + ", got '" + type_name_of(pkg) + "'"

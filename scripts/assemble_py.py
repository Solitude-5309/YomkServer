#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
assemble_py.py —— 构建期源片段合并器

把 src/ 下按职责拆分的源片段按清单顺序合并为单个 Cython 输入文件
（脚本仅依赖标准库，不产生运行时依赖）。

规则:
  1. 每个片段文件头部的连续 import / from 语句统一提取、按首次出现顺序
     去重后置于输出文件头；片段头部（import 之前）的注释原样保留。
  2. 片段主体按命令行给定顺序拼接，每段前插入 `# >>> fragment: <相对路径>`
     标记，便于排障与静态检查回溯。
  3. 禁止相对导入（from .xxx）与 if __name__ == "__main__" 块，出现即失败。
  4. 输出文件头写 `# @generated ...`，禁止手改。

用法:
  python3 scripts/assemble_py.py --output build/YomkServer.py \
      --root <仓库根> src/core/YomkServer.py src/core/YomkService.py ...
"""

import argparse
import os
import sys


def _split_fragment(text):
    """返回 (imports, body)：imports 为文件头连续导入块，body 为其余内容。"""
    lines = text.splitlines(keepends=True)
    i = 0
    pre = []
    # 头部注释/空行随 body 保留（import 之前可能出现片段说明）
    while i < len(lines) and (not lines[i].strip() or lines[i].lstrip().startswith("#")):
        pre.append(lines[i])
        i += 1

    imports = []
    while i < len(lines):
        stripped = lines[i].strip()
        if not stripped or stripped.startswith("#"):
            break
        if not (stripped.startswith("import ") or stripped.startswith("from ")):
            break
        start = i
        depth = lines[i].count("(") - lines[i].count(")")
        i += 1
        while depth > 0 and i < len(lines):
            depth += lines[i].count("(") - lines[i].count(")")
            i += 1
        imports.append("".join(lines[start:i]).rstrip("\n"))

    body = "".join(pre) + "".join(lines[i:])
    return imports, body


def _check_fragment(path, text):
    if any(line.lstrip().startswith("from .") for line in text.splitlines()):
        raise SystemExit("错误: 片段 %s 含相对导入（from .xxx），合并后无法解析" % path)
    if "if __name__ == \"__main__\"" in text or "if __name__ == '__main__'" in text:
        raise SystemExit("错误: 片段 %s 含 __main__ 入口，合并文件禁止" % path)


def main(argv):
    parser = argparse.ArgumentParser(description="合并 YomkServer 源片段")
    parser.add_argument("--output", required=True, help="输出文件路径")
    parser.add_argument("--root", default=os.getcwd(), help="片段相对路径基准（打印标记用）")
    parser.add_argument("fragments", nargs="+", help="源片段清单（顺序即拼接顺序）")
    args = parser.parse_args(argv)

    # 同一 import 只保留首次出现（按语句原文去重）
    seen = set()
    import_lines = []
    bodies = []
    for path in args.fragments:
        if not os.path.isfile(path):
            raise SystemExit("错误: 源片段不存在: %s" % path)
        text = open(path, encoding="utf-8").read()
        _check_fragment(path, text)
        imports, body = _split_fragment(text)
        for stmt in imports:
            key = " ".join(stmt.split())
            if key not in seen:
                seen.add(key)
                import_lines.append(stmt)
        rel = os.path.relpath(path, args.root)
        bodies.append((rel, body.rstrip("\n")))

    out = []
    out.append("# @generated by scripts/assemble_py.py, do not edit.")
    out.append("# fragments: " + ", ".join(rel for rel, _ in bodies))
    out.append("")
    out.extend(import_lines)
    out.append("")
    for rel, body in bodies:
        out.append("")
        out.append("# >>> fragment: " + rel)
        out.append(body)
        out.append("")

    output = os.path.abspath(args.output)
    os.makedirs(os.path.dirname(output) or ".", exist_ok=True)
    with open(output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out).rstrip("\n") + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))